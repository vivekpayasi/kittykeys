import Foundation

/// One emoji in the panel: its default form, the Emoji version that added it, and its five skin-tone
/// variants (light to dark), or none.
public struct EmojiItem: Equatable, Sendable {
    public var base: String
    public var version: Double
    /// Empty, or exactly 5 variants.
    public var skins: [String]

    public init(base: String, version: Double, skins: [String]) {
        self.base = base
        self.version = version
        self.skins = skins
    }
}

/// One section of the panel. `name` is shown to the user and `icon` is an SF Symbol name; both come from data.
public struct EmojiCategory: Equatable, Sendable {
    public var id: String
    public var name: String
    public var icon: String
    public var items: [EmojiItem]

    public init(id: String, name: String, icon: String, items: [EmojiItem]) {
        self.id = id
        self.name = name
        self.icon = icon
        self.items = items
    }
}

/// What `EmojiCatalog.load` returns: the categories in panel order, and the display name of the Recent
/// section, which also comes from data so no user-facing text lives in Swift.
public struct EmojiData: Equatable, Sendable {
    public var recentName: String
    public var categories: [EmojiCategory]

    public init(recentName: String, categories: [EmojiCategory]) {
        self.recentName = recentName
        self.categories = categories
    }
}

/// The bundled emoji list (`emoji.json`, generated by `scripts/make-emoji-data.py`). Nothing is cached here:
/// the caller holds the result while the panel lives and drops it to free memory.
public enum EmojiCatalog {
    public enum LoadError: Error {
        case missingFile(String)
    }

    private struct File: Decodable {
        var recentName: String
        var categories: [Category]
    }

    private struct Category: Decodable {
        var id: String
        var name: String
        var icon: String
        var emoji: [Item]
    }

    private struct Item: Decodable {
        var e: String
        var v: Double
        var s: [String]?
    }

    /// Reads the bundled `emoji.json` and drops every emoji whose version is above `maxVersion`, since iOS
    /// draws those as empty boxes. A skin list that isn't exactly 5 long is dropped, so `skins` is 0 or 5.
    public static func load(maxVersion: Double) throws -> EmojiData {
        guard let url = Bundle.module.url(forResource: "emoji", withExtension: "json") else {
            throw LoadError.missingFile("emoji.json")
        }
        let file = try JSONDecoder().decode(File.self, from: try Data(contentsOf: url))
        let categories = file.categories.map { category in
            EmojiCategory(
                id: category.id,
                name: category.name,
                icon: category.icon,
                items: category.emoji.compactMap { item in
                    guard item.v <= maxVersion else { return nil }
                    let skins = item.s ?? []
                    return EmojiItem(base: item.e, version: item.v, skins: skins.count == 5 ? skins : [])
                }
            )
        }
        return EmojiData(recentName: file.recentName, categories: categories)
    }

    /// The newest Emoji version the given iOS version can draw: 17.0 from iOS 26.4, else 16.0.
    public static func maxSupportedVersion(osMajor: Int, osMinor: Int) -> Double {
        (osMajor, osMinor) >= (26, 4) ? 17.0 : 16.0
    }
}
